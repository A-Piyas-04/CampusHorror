"""Main Gate pavilion: the low building west (left) of the gate tower, with its green bilingual
sign canopy on white cylindrical columns.

Reference: Docs/map-reference/area1/mainGate.jpg. Features: a red-brick room with a brick
corbel band and two pointed-arch windows (white frames, dark glass, grille), a flat canopy
slab running from the room's west end across the porch to the outer edge of the gate arch,
five white cylindrical columns along its front edge, a deep green sign board above the slab
lettered "ISLAMIC UNIVERSITY OF TECHNOLOGY" over the Bengali name, and a short stub of the
brick boundary wall with an end pier beyond the room. Dimensions estimated, not surveyed.

The sign face is UV-mapped to assets/source/blender/textures/main_gate_sign.png, generated by
tools/main_gate_sign_texture.ps1 (Bengali needs complex text shaping, which the pipeline's
Python does not have).

Origin: on the ground at the column line (front of the porch), x = 0 at the gate tower's
west face. The room front is `room_front_y` behind the columns (58 game px of screen depth,
so the room front sits on the gate wall line).
"""

from pathlib import Path

import bmesh

from generators.landmark_common import (arch_outline, brick_shader_material, concrete_material, finish_bmesh,
                                        finish_boxes, glass_material, image_material, paint_material,
                                        steel_material, strip_prism)
from pipeline.modeling import BoxBuilder, add_lathe, extreme_points

COLLECTION_NAME = "MainGatePavilion"

SIGN_TEXTURE = Path(__file__).resolve().parents[1] / "textures" / "main_gate_sign.png"

DEFAULT_PARAMS = {
    "room_x": [-5.875, 0.0],
    "room_front_y": 2.8197,
    "room_back_y": 9.6257,
    "room_height": 3.30,
    "slab_z": [3.30, 3.55],
    "canopy_x": [-7.35, 1.975],       # east end = outer edge of the gate's white arch
    "canopy_front_y": -0.40,
    "roof_back_y": 9.78,
    "sign_z": [3.55, 5.20],
    "sign_thickness": 0.15,
    "column_x": [1.0, -1.0, -3.0, -5.0, -7.0],
    "column_radius": 0.17,
    "window_centres_x": [-3.74, -2.14],
    "window_half_width": 0.45,
    "window_sill_z": 0.95,
    "window_springing_z": 2.0,
    "window_centre_offset": 0.25,
    "frame_width": 0.12,
    "stub_wall_x": [-7.6, -5.875],
    "stub_wall_height": 2.4,
}

WHITE = (0.80, 0.79, 0.75)
SIGN_GREEN = (0.011, 0.077, 0.045)     # linear of sRGB (28, 78, 60), matches the sign texture


def build(collection, rng, params):
    p = params
    rx0, rx1 = p["room_x"]
    fy, by, rh = p["room_front_y"], p["room_back_y"], p["room_height"]
    s0, s1 = p["slab_z"]
    cx0, cx1 = p["canopy_x"]
    brick = brick_shader_material("PavilionBrick", seed=7.0)
    white = paint_material("PavilionWhite", WHITE, roughness=0.7, grime_low=0.7)

    # --- brick: room block with a corbel band, boundary-wall stub with an end pier
    b = BoxBuilder()
    b.add(rx0, rx1, fy, by, 0.0, rh)
    b.add(rx0 - 0.05, rx1, fy - 0.05, by + 0.05, rh - 0.24, rh)
    wx0, wx1 = p["stub_wall_x"]
    b.add(wx0 + 0.45, wx1, fy + 0.05, fy + 0.35, 0.0, p["stub_wall_height"])
    b.add(wx0, wx0 + 0.49, fy - 0.045, fy + 0.445, 0.0, p["stub_wall_height"] + 0.35)
    brick_obj = finish_boxes(collection, "PavilionBrickMass", b, [brick], bevel_width=0.006)

    # --- windows: white pointed frames, dark glass, steel grille
    frames, glass, grille = bmesh.new(), BoxBuilder(), BoxBuilder()
    hw, sill, spring, off, fw = (p["window_half_width"], p["window_sill_z"], p["window_springing_z"],
                                 p["window_centre_offset"], p["frame_width"])
    for wx in p["window_centres_x"]:
        def shifted(pts):
            return [(wx + x, sill + z) for x, z in pts]
        clear = shifted(arch_outline(hw, spring - sill, off))
        strip_prism(frames, clear, shifted(arch_outline(hw + fw, spring - sill, off)), fy - 0.04, fy + 0.02)
        glass.add_prism_xz(clear, fy - 0.012, fy + 0.01)
        apex = max(z for _, z in clear)
        for gx in (wx - hw / 3.0, wx + hw / 3.0):
            glass_top = sill + (apex - sill) * 0.82
            grille.add(gx - 0.012, gx + 0.012, fy - 0.03, fy - 0.012, sill, glass_top)
        grille.add(wx - hw, wx + hw, fy - 0.03, fy - 0.012, spring - 0.012, spring + 0.012)
    sill_boxes = BoxBuilder()
    for wx in p["window_centres_x"]:
        sill_boxes.add(wx - hw - fw - 0.04, wx + hw + fw + 0.04, fy - 0.08, fy + 0.02, sill - 0.08, sill)
    frame_obj = finish_bmesh(collection, "PavilionWindowFrames", frames, [white])
    sill_obj = finish_boxes(collection, "PavilionWindowSills", sill_boxes, [white], bevel_width=0.006)
    glass_obj = finish_boxes(collection, "PavilionWindowGlass", glass, [glass_material()], bevel_width=0.0)
    grille_obj = finish_boxes(collection, "PavilionWindowGrille", grille, [steel_material("PavilionGrille")],
                              bevel_width=0.0)

    # --- canopy slab: porch strip along the columns + roof over the room
    slab = BoxBuilder()
    slab.add(cx0, cx1, p["canopy_front_y"], fy, s0, s1)
    slab.add(rx0 - 0.125, rx1, fy, p["roof_back_y"], s0, s1)
    slab_obj = finish_boxes(collection, "PavilionCanopySlab", slab, [concrete_material("PavilionSlab")],
                            bevel_width=0.008)

    # --- white cylindrical columns with a plain base and capital
    bm = bmesh.new()
    r = p["column_radius"]
    for x in p["column_x"]:
        add_lathe(bm, [(r + 0.05, 0.0), (r + 0.05, 0.12), (r, 0.14), (r, s0 - 0.12), (r + 0.04, s0 - 0.1),
                       (r + 0.04, s0)], sides=24, center=(x, 0.0))
    columns = finish_bmesh(collection, "PavilionColumns", bm, [white], smooth=True)

    # --- sign board: green body; the front face carries the lettering texture
    t, z0, z1 = p["sign_thickness"], *p["sign_z"]
    fy0 = p["canopy_front_y"]
    board = BoxBuilder()
    board.add(cx0, cx1, fy0, fy0 + t, z0, z1)
    board_obj = finish_boxes(collection, "PavilionSignBoard", board,
                             [paint_material("PavilionSignGreen", SIGN_GREEN, roughness=0.55, variation=0.05,
                                             grime_low=1.0)], bevel_width=0.01)
    bm = bmesh.new()
    uv = bm.loops.layers.uv.new("UVMap")
    face = bm.faces.new([bm.verts.new(c) for c in ((cx0, fy0 - 0.002, z0), (cx1, fy0 - 0.002, z0),
                                                   (cx1, fy0 - 0.002, z1), (cx0, fy0 - 0.002, z1))])
    for loop, coord in zip(face.loops, ((0, 0), (1, 0), (1, 1), (0, 1))):
        loop[uv].uv = coord
    mesh_face = finish_bmesh(collection, "PavilionSignFace", bm, [image_material("PavilionSign", SIGN_TEXTURE)])

    objects = [brick_obj, frame_obj, sill_obj, glass_obj, grille_obj, slab_obj, columns, board_obj, mesh_face]
    return {
        "objects": objects,
        "bounds_points_m": extreme_points(objects),
        "footprint_m": [wx0, cx1, p["canopy_front_y"], p["roof_back_y"]],
        "info": {
            "design_size_m": {"width_x": round(cx1 - wx0, 4), "depth_y": round(p["roof_back_y"] - fy0, 4),
                              "height_z": z1},
            "room_m": {"x": [rx0, rx1], "y": [fy, by], "height": rh},
            "sign_texture": "assets/source/blender/textures/main_gate_sign.png "
                            "(tools/main_gate_sign_texture.ps1)",
            "materials": ["PavilionBrick", "PavilionWhite", "PavilionSlab", "PavilionSignGreen", "PavilionSign",
                          "WindowGlass", "PavilionGrille"],
            "connection_point": "origin = column line at the gate tower's west face; place the node 58 game px "
                                "south of the wall line so the room front sits on it",
            "reference": "Docs/map-reference/area1/mainGate.jpg; dimensions estimated, not surveyed",
        },
    }
