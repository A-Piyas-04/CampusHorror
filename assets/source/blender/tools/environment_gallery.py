"""TEMPORARY: writes scenes/tests/asset_previews/EnvironmentGalleryTest.tscn, the Milestone G
gallery of the first environment batch at gameplay scale (zoom 1, 32 px = 1 m).

    python assets/source/blender/tools/environment_gallery.py

A small campus corner: lawn with worn patches, an E-W paved walkway with a N-S branch through
a red-brick doorway run, a road along the south, hedges on the verge, benches, lamp posts,
broadleaf trees and palms. Ground is one TileMapLayer on the campus_ground TileSet (2 m tiles);
everything else is an instance of a generated prop scene. Safe to delete with the gallery.
"""

import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from pipeline import conventions as C  # noqa: E402
from pipeline.godot_scene import tile_map_data, vec2  # noqa: E402

OUT = C.PROJECT_ROOT / "scenes/tests/asset_previews/EnvironmentGalleryTest.tscn"
GRASS, WORN, PAVED, ROAD = 0, 1, 2, 3

EXT = [
    ("Script", "res://scenes/tests/asset_previews/environment_gallery_test.gd", "1_script"),
    ("TileSet", "res://assets/tilesets/campus_ground.tres", "2_ground"),
    ("PackedScene", "res://scenes/props/vegetation/BroadleafTree.tscn", "3_tree"),
    ("PackedScene", "res://scenes/props/vegetation/CoconutPalm.tscn", "4_palm"),
    ("PackedScene", "res://scenes/props/vegetation/HedgeSection2m.tscn", "5_hedge"),
    ("PackedScene", "res://scenes/props/street_furniture/OutdoorBench.tscn", "6_bench"),
    ("PackedScene", "res://scenes/props/street_furniture/LampPost.tscn", "7_lamp"),
    ("PackedScene", "res://scenes/props/architecture/RedBrickWall3m.tscn", "8_wall"),
    ("PackedScene", "res://scenes/props/architecture/RedBrickArchDoorway3m.tscn", "9_doorway"),
    ("PackedScene", "res://scenes/props/architecture/RedBrickArchWindow3m.tscn", "10_window"),
    ("PackedScene", "res://scenes/props/architecture/RedBrickVerandaPier.tscn", "11_pier"),
]


def ground_cells():
    worn = {(-4, 0), (1, 0), (5, 0), (-2, 0), (-6, 2), (2, 2), (-3, 2)}
    cells = []
    for y in range(-6, 6):
        for x in range(-10, 10):
            if y >= 4:
                src = ROAD
            elif y == 1 or (x == -3 and y <= 0):
                src = PAVED
            elif (x, y) in worn:
                src = WORN
            else:
                src = GRASS
            cells.append((x, y, src))
    return cells


def objects():
    """(name, ext id, position) in game px; origins are ground footprints."""
    o = []
    for name, ext, x in (("Wall", "8_wall", -256), ("Doorway", "9_doorway", -160), ("Window", "10_window", -64),
                         ("WallEast", "8_wall", 32)):
        o.append((f"Brick{name}", ext, (x, -200)))
    for k, x in enumerate((-304, -208, -112, -16, 80)):
        o.append((f"Pier{k}", "11_pier", (x, -200)))
    o += [("BroadleafTreeEast", "3_tree", (256, -110)), ("BroadleafTreeWest", "3_tree", (-480, -70)),
          ("PalmNorthEast", "4_palm", (432, -120)), ("PalmVergeWest", "4_palm", (-96, 196)),
          ("PalmVergeEast", "4_palm", (96, 196))]
    for i, x in enumerate(range(-544, -159, 64)):
        o.append((f"HedgeWest{i}", "5_hedge", (x, 232)))
    for i, x in enumerate(range(160, 545, 64)):
        o.append((f"HedgeEast{i}", "5_hedge", (x, 232)))
    o += [("BenchWest", "6_bench", (-224, 40)), ("BenchMiddle", "6_bench", (96, 40)),
          ("BenchEast", "6_bench", (352, 40))]
    o += [(f"Lamp{k}", "7_lamp", (x, 58)) for k, x in enumerate((-416, -96, 224, 480))]
    return o


def main():
    parts = ["[gd_scene format=3]\n"]
    parts.append("".join(f'[ext_resource type="{t}" path="{p}" id="{i}"]\n' for t, p, i in EXT))
    parts.append(
        '[node name="EnvironmentGalleryTest" type="Node2D"]\n'
        'editor_description = "TEMPORARY Milestone G gallery: the first environment batch (4 ground tiles, '
        'broadleaf tree, coconut palm, hedge, bench, lamp post) with the red-brick architecture at gameplay scale '
        '(camera zoom 1, 32 px = 1 m). Generated by assets/source/blender/tools/environment_gallery.py. '
        'The script sweeps a player footprint past each object and prints [GALLERY] results. '
        'Not part of the game; safe to delete."\n'
        'y_sort_enabled = true\n'
        'script = ExtResource("1_script")\n')
    parts.append(
        '[node name="Ground" type="TileMapLayer" parent="."]\n'
        'z_index = -10\n'
        f'tile_map_data = {tile_map_data(ground_cells())}\n'
        'tile_set = ExtResource("2_ground")\n')
    parts.append('[node name="Objects" type="Node2D" parent="."]\ny_sort_enabled = true\n')
    for name, ext, (x, y) in objects():
        parts.append(f'[node name="{name}" parent="Objects" instance=ExtResource("{ext}")]\n'
                     f'position = {vec2(x, y)}\n')
    for name, (x, y) in (("ScaleReferenceOnWalkway", (-32, 112)), ("ScaleReferenceByTree", (300, -96))):
        parts.append(
            f'[node name="{name}" type="Polygon2D" parent="Objects"]\n'
            'editor_description = "Blue 32x64 player-sized reference (2 m), feet at its origin."\n'
            f'position = {vec2(x, y)}\n'
            'color = Color(0.2, 0.35, 0.8, 0.6)\n'
            'polygon = PackedVector2Array(-16, -64, 16, -64, 16, 0, -16, 0)\n')
    parts.append('[node name="Camera" type="Camera2D" parent="."]\n'
                 'editor_description = "TEMPORARY camera at gameplay zoom 1 (same as Player/Camera)."\n'
                 'position = Vector2(0, -16)\n')
    OUT.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(OUT)


if __name__ == "__main__":
    main()
