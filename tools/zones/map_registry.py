"""Regenerates the zone / transition / spawn registry in Docs/CAMPUS_MAP.md from the zone scenes themselves.

    python tools/zones/map_registry.py

Reads data/zones/zone_registry.tres and every registered scene; writes the block between
<!-- registry:begin --> and <!-- registry:end -->. Doors (interact) and edges (walk-off) both appear as transitions.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "Docs/CAMPUS_MAP.md"
BEGIN, END = "<!-- registry:begin -->", "<!-- registry:end -->"


def registry():
    s = (ROOT / "data/zones/zone_registry.tres").read_text(encoding="utf-8")
    body = s[s.index("({") + 2:s.index("})")]
    out = {}
    for line in body.strip().splitlines():
        line = line.strip().rstrip(",")
        if line:
            k, v = line.split(":", 1)
            out[json.loads(k.strip())] = json.loads(v.strip())
    return out


def nodes(path):
    """(name, parent, instance path, props) for every node of a .tscn."""
    text = path.read_text(encoding="utf-8")
    ext = dict((m.group(2), m.group(1)) for m in re.finditer(r'\[ext_resource [^\]]*path="([^"]+)" id="([^"]+)"\]', text))
    out = []
    for block in re.split(r"\n(?=\[)", text):
        m = re.match(r'\[node name="([^"]+)"([^\]]*)\]', block)
        if not m:
            continue
        head = m.group(2)
        parent = re.search(r'parent="([^"]*)"', head)
        inst = re.search(r'instance=ExtResource\("([^"]+)"\)', head)
        props = {}
        for line in block.splitlines()[1:]:
            if " = " in line:
                k, v = line.split(" = ", 1)
                props[k.strip()] = v.strip()
        out.append((m.group(1), parent.group(1) if parent else None, ext.get(inst.group(1)) if inst else None, props))
    return out


def unq(v):
    try:
        return json.loads(v)
    except (ValueError, TypeError):
        return v


def main():
    reg = registry()
    zones, trans, spawns = [], [], []
    for zid, scene in sorted(reg.items()):
        p = ROOT / scene.replace("res://", "")
        if not p.exists():
            zones.append((zid, scene, "MISSING"))
            continue
        ns = nodes(p)
        n_doors = 0
        for name, parent, inst, props in ns:
            if "destination_zone_id" in props:
                kind = "edge" if inst and inst.endswith("ZoneEdge.tscn") else "door"
                locked = ""
                if unq(props.get("requires_flag", '""')) or unq(props.get("required_item", '""')):
                    locked = f"needs {unq(props.get('requires_flag', '')) or unq(props.get('required_item', ''))}"
                trans.append((zid, name, kind, props.get("position", "(nested)"), unq(props["destination_zone_id"]),
                              unq(props.get("destination_spawn_id", '""')), unq(props.get("place_name", '""')), locked))
                n_doors += 1
            if "spawn_id" in props:
                spawns.append((zid, unq(props["spawn_id"]), props.get("position", "(nested)")))
        zones.append((zid, scene, f"{len(ns)} nodes, {n_doors} transitions"))

    known = {(z, s) for z, s, _ in spawns}
    lines = [BEGIN, "", "_Generated by `python tools/zones/map_registry.py` from the zone scenes; do not edit by hand._", "",
             "### Zones", "", "| zone_id | Scene | Size |", "|---|---|---|"]
    lines += [f"| `{z}` | `{s.replace('res://', '')}` | {info} |" for z, s, info in zones]
    lines += ["", "### Transitions (doors = interact; edges = walk into the strip)", "",
              "| From | Node | Kind | Position | To zone | To spawn | Place | Lock |", "|---|---|---|---|---|---|---|---|"]
    for z, n, k, pos, dz, ds, place, locked in trans:
        bad = "" if (dz, ds) in known else " **(spawn missing)**"
        lines.append(f"| `{z}` | {n} | {k} | {pos.replace('Vector2', '')} | `{dz}` | `{ds}`{bad} | {place} | {locked} |")
    lines += ["", "### Spawns", "", "| Zone | spawn_id | Position |", "|---|---|---|"]
    lines += [f"| `{z}` | `{s}` | {pos.replace('Vector2', '')} |" for z, s, pos in spawns]
    lines += ["", END]
    block = "\n".join(lines)

    doc = DOC.read_text(encoding="utf-8")
    if BEGIN in doc:
        doc = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    else:
        raise SystemExit(f"markers {BEGIN} / {END} not found in {DOC}")
    DOC.write_text(doc, encoding="utf-8")
    missing = [t for t in trans if (t[4], t[5]) not in known]
    print(f"registry: {len(zones)} zones, {len(trans)} transitions, {len(spawns)} spawns, {len(missing)} broken")
    for t in missing:
        print("  BROKEN", t)
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
